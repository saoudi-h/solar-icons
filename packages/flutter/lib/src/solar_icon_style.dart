/// The six Solar icon styles.
enum SolarIconStyle {
  /// Filled shapes.
  bold,

  /// Filled shapes with a second color on the accent layer.
  boldDuotone,

  /// Stroke icon with a broken contour.
  broken,

  /// Stroke icon. This is the default style.
  linear,

  /// Stroke icon with a second color on the accent layer.
  lineDuotone,

  /// Heavier stroke icon.
  outline,
}
