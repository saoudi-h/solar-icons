import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

import { readCoreMetadata } from './catalog-source'

const oxfmtFormat = (filepath: string, code: string): string =>
    execFileSync(
        path.join(import.meta.dirname, '../../../node_modules/.bin/oxfmt'),
        ['--stdin-filepath', filepath],
        { input: code, encoding: 'utf8' }
    )

interface MetadataCatalog {
    categories: Record<string, { icons: string[] }>
}

interface RegistryManifest {
    packages: unknown[]
}

const metadata = readCoreMetadata<MetadataCatalog>('metadata.json')
const registryPath = path.resolve(import.meta.dirname, '../../../registry.json')
const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8')) as RegistryManifest

const outputUtilsFilePath = './generated/utils.ts'

const generateIcons = (metadata: MetadataCatalog, packageCount: number) => {
    const styles = ['Broken', 'Outline', 'Linear', 'Bold', 'LineDuotone', 'BoldDuotone'] as const
    const categories = Object.keys(metadata.categories)
    const iconCount = Object.values(metadata.categories).reduce(
        (sum, category) => sum + category.icons.length,
        0
    )
    const styleCount = styles.length
    const variationCount = iconCount * styleCount

    let utils = `/* Generated by scripts/generate-data.ts */

export const styles = ['Broken', 'Outline', 'Linear', 'Bold', 'LineDuotone', 'BoldDuotone'] as const
export type Style = (typeof styles)[number]

`
    utils += `export const categories = ${JSON.stringify(categories)} as const\n`
    utils += 'export type Category = typeof categories[number]\n\n'
    utils += `export const catalogStats = {
    iconCount: ${iconCount},
    styleCount: ${styleCount},
    variationCount: ${variationCount},
    categoryCount: ${categories.length},
    packageCount: ${packageCount},
    formattedIconCount: ${JSON.stringify(iconCount.toLocaleString('en-US'))},
    formattedVariationCount: ${JSON.stringify(variationCount.toLocaleString('en-US'))},
} as const
`

    return { utils }
}

const main = async () => {
    try {
        const { utils } = generateIcons(metadata, registry.packages.length)
        console.log('The file generated/utils.ts has been generated with success !')
        fs.writeFileSync(outputUtilsFilePath, oxfmtFormat(outputUtilsFilePath, utils))
    } catch (error) {
        console.error('Error while generating the file:', error)
        process.exitCode = 1
    }
}

main()
