import icons from '@solar-icons/core/metadata-descriptions.json' assert { type: 'json' }
import fs from 'node:fs'
import prettier from 'prettier'

const outputDataFilePath = './generated/descriptions.ts'

const toPascalCase = (str: string) =>
    str
        .split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1))
        .join('')

type IconData = {
    name: string
    category: string
    categoryTags: string[]
    tags: string[]
    deprecatedAliases?: {
        name: string
        replacement: string
        reason: string
        deprecatedSince?: string
    }[]
}

const generate = (iconsData: IconData[]): string => {
    const iconEntries = Object.values(iconsData)
    const uniqueIcons = Array.from(new Set(iconEntries.map(icon => toPascalCase(icon.name)))).sort()

    let data = `/* Generated by scripts/generate-descriptions.ts */

import { ${uniqueIcons.map(n => `${n}Icon`).join(', ')} } from '@solar-icons/react/dynamic'
import type { ComponentType } from 'react'
import type { Weight } from '@solar-icons/core'
import type { IconProps } from '@solar-icons/react/lib/types'
import type { Category } from './utils'

export interface IconData {
    name: string
    category: Category
    categoryTags: string[]
    tags: string[]
    deprecatedAliases?: {
        name: string
        replacement: string
        reason: string
        deprecatedSince?: string
    }[]
    Icon: ComponentType<{ weight?: Weight } & IconProps>
}

export const icons: IconData[] = [
`
    const res = iconEntries.map(icon => {
        const componentName = toPascalCase(icon.name) + 'Icon'
        const deprecatedAliases = icon.deprecatedAliases?.length
            ? `         deprecatedAliases: ${JSON.stringify(icon.deprecatedAliases)},\n`
            : ''
        return `    {
        name: '${icon.name}',
        category: '${icon.category}' as Category,
         categoryTags: ${JSON.stringify(icon.categoryTags)},
         tags: ${JSON.stringify(icon.tags)},
${deprecatedAliases}         Icon: ${componentName},
    }`
    })

    data += res.join(',\n')
    data += `\n]

export default icons
`

    return data
}

const main = async () => {
    try {
        const data = generate(icons)
        fs.writeFileSync(
            outputDataFilePath,
            await prettier.format(data, {
                ...(await prettier.resolveConfig(outputDataFilePath)),
                parser: 'typescript',
            })
        )
        console.log('The file has been generated with success !')
    } catch (error) {
        console.error('Error while generating the file:', error)
    }
}

main()
