import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

import { readCoreMetadata } from './catalog-source'

const oxfmtFormat = (filepath: string, code: string): string =>
    execFileSync(
        path.join(import.meta.dirname, '../../../node_modules/.bin/oxfmt'),
        ['--stdin-filepath', filepath],
        { input: code, encoding: 'utf8' }
    )

const outputFilePath = './generated/categories.ts'
const outputIconsFilePath = './generated/categoryIcons.ts'
const pagePath = './content/docs/v2/icon-reference/categories.mdx'
const START_MARKER = '{/* categories:generated:start */}'
const END_MARKER = '{/* categories:generated:end */}'

const toPascalCase = (str: string) =>
    str
        .split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1))
        .join('')

/**
 * Representative icon for each category, shown as the thumbnail on the
 * categories page. Curated by hand: the first icon of a category in
 * catalogue order is rarely the one that reads best in a grid (the
 * `arrows` category starts with `alt-arrow-down`, the `settings`
 * category with `columns-2`).
 *
 * A stale entry here falls back to the first icon of the category and
 * prints a warning. `scripts/check-icon-inventory.ts` fails the build
 * in CI when a curated icon disappears, so a rename never ships silently.
 */
const REPRESENTATIVE_ICONS: Record<string, string> = {
    arrows: 'arrow-right',
    'arrows-action': 'download',
    astronomy: 'planet',
    building: 'city',
    business: 'chart',
    call: 'phone',
    devices: 'laptop',
    faces: 'smile-circle',
    files: 'file-text',
    folders: 'folder',
    food: 'chef-hat',
    hands: 'hand-heart',
    home: 'sofa',
    it: 'code',
    like: 'heart',
    list: 'checklist',
    map: 'compass',
    medicine: 'medical-kit',
    messages: 'chat-round',
    money: 'banknote',
    nature: 'leaf',
    notes: 'notebook',
    notifications: 'bell',
    parts: 'car',
    school: 'backpack',
    search: 'magnifier',
    security: 'shield-check',
    settings: 'tuning',
    shopping: 'cart',
    sports: 'basketball',
    'text-formatting': 'text-bold',
    time: 'clock-circle',
    tools: 'palette',
    ui: 'cursor',
    users: 'user',
    video: 'play-circle',
    weather: 'sun',
}

/** Human-readable labels. Everything else is title-cased from the slug. */
const LABELS: Record<string, string> = {
    'arrows-action': 'Arrows Action',
    it: 'IT',
    'text-formatting': 'Text Formatting',
    ui: 'UI',
}

const titleCase = (slug: string): string =>
    LABELS[slug] ??
    slug
        .split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1))
        .join(' ')

interface CategoryMeta {
    icons: string[]
}

const main = async () => {
    const metadata = readCoreMetadata<{ categories: Record<string, CategoryMeta> }>('metadata.json')
    const warnings: string[] = []

    const entries = Object.entries(metadata.categories).map(([slug, data]) => {
        const curated = REPRESENTATIVE_ICONS[slug]
        let representative = curated ?? data.icons[0]

        if (curated && !data.icons.includes(curated)) {
            warnings.push(
                `representative icon "${curated}" is no longer in category "${slug}", falling back to "${data.icons[0]}"`
            )
            representative = data.icons[0]
        }

        if (!representative) {
            warnings.push(`category "${slug}" has no icon to represent it`)
            representative = ''
        }

        return {
            slug,
            label: titleCase(slug),
            count: data.icons.length,
            representative,
        }
    })

    const componentNames = entries.map(entry => `${toPascalCase(entry.representative)}Icon`)
    const uniqueComponentNames = Array.from(new Set(componentNames)).sort()

    // Data only, no import: the inventory check script reads this
    // module to compare the published categories with the catalogue.
    let output = `/* Generated by scripts/generate-categories.ts */

export interface CategoryCardData {
    /** Catalogue slug, e.g. \`arrows-action\`. */
    slug: string
    /** Human-readable label, e.g. \`Arrows Action\`. */
    label: string
    /** Number of logical icons in the category. */
    count: number
    /** Icon name used as the category thumbnail, e.g. \`arrow-right\`. */
    representative: string
}

export const categoryCards: CategoryCardData[] = [
`
    for (const entry of entries) {
        output += `    {
        slug: '${entry.slug}',
        label: '${entry.label}',
        count: ${entry.count},
        representative: '${entry.representative}',
    },
`
    }
    output += `]

export const categoryCount = categoryCards.length
`

    let iconsOutput = `/* Generated by scripts/generate-categories.ts */

import { ${uniqueComponentNames.join(', ')} } from '@solar-icons/react/dynamic'
import type { Weight } from '@solar-icons/core'
import type { IconProps } from '@solar-icons/react/lib/types'
import type { ComponentType } from 'react'

export type CategoryIcon = ComponentType<{ weight?: Weight } & IconProps>

export const categoryIcons: Record<string, CategoryIcon> = {
`
    for (const entry of entries) {
        const componentName = `${toPascalCase(entry.representative)}Icon`
        iconsOutput += `    '${entry.representative}': ${componentName} as CategoryIcon,\n`
    }
    iconsOutput += `}
`

    fs.writeFileSync(outputFilePath, oxfmtFormat(outputFilePath, output))
    fs.writeFileSync(outputIconsFilePath, oxfmtFormat(outputIconsFilePath, iconsOutput))
    writePageBlock(entries)
    for (const warning of warnings) console.warn(`Warning: ${warning}`)
    console.log(
        `The files generated/categories.ts and generated/categoryIcons.ts have been generated with success ! (${entries.length} categories)`
    )
}

/**
 * The categories page also carries a textual form of the list, between
 * the `categories:generated` markers. It is what `/llms-full.txt` and
 * the "Copy Markdown" button expose, so the machine-readable surface
 * lists the same categories as the page.
 *
 * The file is only written when its content changes: the build runs
 * this script, and a rewrite would move the "last updated" date of the
 * page on every build.
 */
function writePageBlock(entries: { slug: string; label: string; count: number }[]) {
    if (!fs.existsSync(pagePath)) {
        console.warn(`Warning: ${pagePath} is absent, skipping the generated block`)
        return
    }

    const content = fs.readFileSync(pagePath, 'utf8')
    const start = content.indexOf(START_MARKER)
    const end = content.indexOf(END_MARKER)
    if (start === -1 || end === -1 || end < start) {
        console.warn(`Warning: ${pagePath} has no ${START_MARKER} / ${END_MARKER} markers`)
        return
    }

    const rows = entries
        .map(
            entry =>
                `| [${entry.label}](/icons?view=grouped&category=${entry.slug}) | ${entry.count} |`
        )
        .join('\n')

    const block = `${START_MARKER}
<details>
<summary>Text list of the categories</summary>

| Category | Icons |
| -------- | ----- |
${rows}

</details>
${END_MARKER}`

    const next = content.slice(0, start) + block + content.slice(end + END_MARKER.length)
    // The page is formatted like the rest of the repository, so the
    // generated block matches what `oxfmt` produces.
    const formatted = oxfmtFormat(pagePath, next)
    if (formatted === content) return
    fs.writeFileSync(pagePath, formatted)
    console.log('The generated block of the categories page has been refreshed.')
}

main()
