import fs from 'node:fs'
import prettier from 'prettier'
import { readCoreMetadata } from './catalog-source'

const metadata = readCoreMetadata<{ categories: Record<string, unknown> }>('metadata.json')

const toPascalCase = (str: string) =>
    str
        .split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1))
        .join('')

const outputUtilsFilePath = './generated/utils.ts'

const generateIcons = (metadata: any) => {
    let utils = `/* Generated by scripts/generate-data.ts */

export const styles = ['Broken', 'Outline', 'Linear', 'Bold', 'LineDuotone', 'BoldDuotone'] as const
export type Style = (typeof styles)[number] 

`
    const categories = Object.keys(metadata.categories)
    utils += `export const categories = ${JSON.stringify(categories)} as const\n`
    utils += 'export type Category = typeof categories[number]'

    return { utils }
}

const main = async () => {
    try {
        const { utils } = generateIcons(metadata)
        console.log('The file generated/utils.ts has been generated with success !')
        fs.writeFileSync(
            outputUtilsFilePath,
            await prettier.format(utils, {
                ...(await prettier.resolveConfig(outputUtilsFilePath)),
                parser: 'typescript',
            })
        )
    } catch (error) {
        console.error('Error while generating the file:', error)
    }
}

main()
