import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

import { readCoreMetadata } from './catalog-source'

const oxfmtFormat = (filepath: string, code: string): string =>
    execFileSync(
        path.join(import.meta.dirname, '../../../node_modules/.bin/oxfmt'),
        ['--stdin-filepath', filepath],
        { input: code, encoding: 'utf8' }
    )

const metadata = readCoreMetadata<{ categories: Record<string, { icons: string[] }> }>(
    'metadata.json'
)

const toPascalCase = (str: string) =>
    str
        .split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1))
        .join('')

/**
 * Takes `count` icons starting at `start`, wrapping around to the
 * beginning when the category runs out — short categories reuse their
 * own icons so rings always render full.
 */
const takeCycled = (icons: string[], start: number, count: number): string[] => {
    if (icons.length === 0) return []
    const out: string[] = []
    for (let i = 0; i < count; i++) {
        out.push(icons[(start + i) % icons.length]!)
    }
    return out
}

const outputFilePath = './generated/generatedHeroUtils.ts'
const generateIconsByCategory = (data: any) => {
    const categories = data.categories
    const categoryList: string[] = []
    const allIconsSet = new Set<string>()
    let categoryBodies = ''

    Object.entries(categories).forEach(([categoryName, categoryData]: [string, any]) => {
        const icons = categoryData.icons

        // Check that there are at least 17 icons for the category so it
        // stays in the rotation (same gate as before doubling).
        if (icons.length < 17) return
        const categoryPascalCase = toPascalCase(categoryName)
        categoryList.push(categoryPascalCase)

        // Separates icons into internal (14) and external (20) — twice the
        // previous 7 + 10. Categories shorter than 34 icons reuse their own
        // icons from the top (`takeCycled`) so both rings always render
        // full instead of leaving visible gaps.
        const innerIconsNames = takeCycled(icons, 0, 14).map((icon: string) => toPascalCase(icon))
        const outerIconsNames = takeCycled(icons, 14, 20).map((icon: string) => toPascalCase(icon))

        innerIconsNames.forEach((name: string) => allIconsSet.add(name))
        outerIconsNames.forEach((name: string) => allIconsSet.add(name))

        categoryBodies += `
    case '${categoryPascalCase}':
      return {
        inner: [
          ${innerIconsNames.map(n => `${n}Icon`).join(',\n          ')}
        ],
        outer: [
          ${outerIconsNames.map(n => `${n}Icon`).join(',\n          ')}
        ],
      };`
    })

    const sortedImports = Array.from(allIconsSet).sort()

    let output = `/* Generated by generateHeroUtils.ts */
import { ${sortedImports.map(n => `${n}Icon`).join(', ')} } from '@solar-icons/react/dynamic'
import type { ComponentType } from 'react'
import type { IconProps } from '@solar-icons/react/lib/types'
import type { Weight } from '@solar-icons/core'

export const styles = ['Broken', 'Outline', 'Linear', 'Bold', 'LineDuotone', 'BoldDuotone'] as const
export type Style = (typeof styles)[number]

export const getIconsByCategory = (category: string) => {
  switch (category) {${categoryBodies}
    default:
      return {
        inner: [],
        outer: [],
      };
  }
}

export const categories = ${JSON.stringify(categoryList)} as const
export type Category = typeof categories[number]
`

    return output
}

const main = async () => {
    try {
        const outputContent = generateIconsByCategory(metadata)
        fs.writeFileSync(outputFilePath, oxfmtFormat(outputFilePath, outputContent))
        console.log('The file generated/generatedHeroUtils.ts has been generated successfully !')
    } catch (error) {
        console.error('Error generating file :', error)
    }
}

main()
